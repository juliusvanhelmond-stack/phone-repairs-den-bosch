/**
 * Step 5 — generate the auditable migration documents:
 *   docs/content-inventory.md, docs/url-mapping.csv, docs/data-gaps.md
 *
 * Combines the seed inventory, discovery/crawl output (if any), the parsed
 * analysis (if any) and the site's content data. Re-run after every crawl.
 *
 * Usage: npm run report
 */
import { join } from "node:path";
import { blogPosts, brands, categories, claims, devices, faqs, landingPages, prices, repairs, warranties } from "../../src/lib/catalog";
import { site } from "../../src/lib/site";
import type { UrlRecord } from "../../src/types/content";
import inventoryJson from "../../src/data/url-inventory.json";
import { readJson, writeText } from "../lib/io";
import { DOCS_DIR, files } from "../lib/paths";

type Discovered = { generatedAt: string; status: string; blockedReason?: string; urls: { url: string; discoveredVia: string }[] };
type Analysis = {
  generatedAt: string;
  pages: number;
  cms: string[];
  duplicates: string[][];
  priceCandidates: number;
  priceConflicts: { key: string; amounts: number[] }[];
  unmatchedPrices: unknown[];
  warrantyDurations: Record<string, string[]>;
  contactValues: { phones: string[]; emails: string[]; whatsapp: string[] };
  pagesWithoutDevice: string[];
};
type FetchLog = { entries: { url: string; status: number | string }[] };

const seed = inventoryJson as UrlRecord[];
const discovered = readJson<Discovered | null>(files.discovered, null);
const analysis = readJson<Analysis | null>(files.analysis, null);
const fetchLog = readJson<FetchLog | null>(files.fetchLog, null);
const httpStatus = new Map((fetchLog?.entries ?? []).map((e) => [e.url, e.status]));

const records: UrlRecord[] = [...seed];
for (const d of discovered?.urls ?? []) {
  if (!records.some((r) => r.url === d.url))
    records.push({
      url: d.url,
      discoveredVia: d.discoveredVia as UrlRecord["discoveredVia"],
      pageType: "unknown",
      status: "discovered",
      targetPath: null,
      redirect: false,
    });
}
records.sort((a, b) => a.url.localeCompare(b.url));

const count = <T,>(list: T[], key: (t: T) => string) =>
  list.reduce<Record<string, number>>((acc, t) => ((acc[key(t)] = (acc[key(t)] ?? 0) + 1), acc), {});
const table = (head: string[], rows: (string | number)[][]) =>
  [`| ${head.join(" | ")} |`, `| ${head.map(() => "---").join(" | ")} |`, ...rows.map((r) => `| ${r.join(" | ")} |`)].join("\n");
const esc = (s?: string | null) => (s ?? "").replace(/\|/g, "\\|");
const csv = (v: unknown) => `"${String(v ?? "").replace(/"/g, '""')}"`;

const discoveryLine = discovered
  ? `Discovery run ${discovered.generatedAt}: **${discovered.status}**${discovered.blockedReason ? ` (${discovered.blockedReason})` : ""}, ${discovered.urls.length} URLs.`
  : "Discovery has **not run successfully** yet in this environment: www.phonerepairs.nl is blocked by the network policy. Inventory below is based on public search-engine snapshots only.";

// --- content-inventory.md ----------------------------------------------------
const verification = (list: { sources: { verification: string }[] }[]) =>
  count(list, (r) => r.sources.map((s) => s.verification).sort().at(-1) ?? "none");

const inventoryMd = `# Content inventory

_Generated by \`npm run report\`. Do not edit by hand._

${discoveryLine}

The original site reportedly has 1,000+ pages. **${records.length} URLs are currently known**, so this inventory is
**not complete** and must not be read as proof of migration.

## URLs by status

${table(["Status", "Count"], Object.entries(count(records, (r) => r.status)).map(([k, v]) => [k, v]))}

## URLs by page type

${table(["Page type", "Count"], Object.entries(count(records, (r) => r.pageType)).map(([k, v]) => [k, v]))}

## Known URLs

${table(
  ["Original URL", "Type", "Found via", "Status", "New path", "Notes"],
  records.map((r) => [new URL(r.url).pathname, r.pageType, r.discoveredVia, r.status, r.targetPath ?? "—", esc(r.notes)]),
)}

## Site content data (src/data)

${table(
  ["Dataset", "Records", "Verification (highest per record)"],
  [
    ["Categories", categories.length, "structural"],
    ["Brands", brands.length, JSON.stringify(verification(brands))],
    ["Devices (seed catalog)", devices.length, JSON.stringify(verification(devices))],
    ["Repair services", repairs.length, JSON.stringify(verification(repairs))],
    ["Prices", prices.length, `${prices.filter((p) => p.verified).length} verified`],
    ["Warranty records", warranties.length, `${warranties.filter((w) => w.verified).length} verified`],
    ["Claims (trust section)", claims.length, JSON.stringify(verification(claims))],
    ["FAQs", faqs.length, JSON.stringify(verification(faqs))],
  ],
)}

Verification levels: \`verified-source\` (extracted from the live page), \`search-index\` (seen in a search-engine
snapshot of the original page — confirm before launch), \`owner-confirmed\`, \`demo\` (JUNE Studio placeholder).

## Devices per brand

${table(
  ["Brand", ...categories.map((c) => c.plural), "Total"],
  brands.map((b) => [
    b.name,
    ...categories.map((c) => devices.filter((d) => d.brandId === b.id && d.categoryId === c.id).length),
    devices.filter((d) => d.brandId === b.id).length,
  ]),
)}
${
  analysis
    ? `\n## Crawl analysis (${analysis.generatedAt})\n\n- Parsed pages: ${analysis.pages}\n- CMS detected: ${analysis.cms.join(", ") || "unknown"}\n- Duplicate content groups: ${analysis.duplicates.length}\n- Price candidates awaiting review: ${analysis.priceCandidates}\n`
    : ""
}`;

// --- url-mapping.csv ---------------------------------------------------------
const csvRows = [
  ["old_url", "old_path", "page_type", "discovered_via", "migration_status", "new_path", "redirect_301", "http_status", "notes"],
  ...records.map((r) => [
    r.url,
    new URL(r.url).pathname,
    r.pageType,
    r.discoveredVia,
    r.status,
    r.targetPath ?? "",
    r.redirect ? "yes" : "no",
    httpStatus.get(r.url) ?? "not fetched",
    r.notes ?? "",
  ]),
];
const mappingCsv = csvRows.map((row) => row.map(csv).join(",")).join("\n") + "\n";

// --- data-gaps.md ------------------------------------------------------------
const demoRepairs = repairs.filter((r) => r.sources.every((s) => s.verification === "demo"));
const demoBrandsDevices = devices.filter((d) => d.sources.every((s) => s.verification === "demo"));
const unmapped = records.filter((r) => !r.targetPath);

const crawlConflictRows = analysis
  ? [
      ...analysis.priceConflicts.map((c) => `| Price ${c.key} | ${c.amounts.join(" / ")} | crawl | Not published until reviewed |`),
      ...(Object.keys(analysis.warrantyDurations).length > 1
        ? [`| Warranty durations (crawl) | ${Object.keys(analysis.warrantyDurations).join(", ")} | crawl | Review with owner |`]
        : []),
    ].join("\n")
  : "";

const gapsMd = `# Data gaps, conflicts and open questions

_Generated by \`npm run report\`. Do not edit by hand; edit the data or scripts/validation/report.ts._

## 1. Access limitation

${discoveryLine}

Consequence: no page of the original site has been fetched or parsed yet. Everything on the demo comes from
search-engine snapshots (marked \`search-index\`) or is clearly marked demo content. **No prices are shown.**

Permission: on 2026-10-12 the client allowed JUNE Studio to copy all content of the current site verbatim
(texts, prices including "op aanvraag", opening hours). Values copied from the live pages count as \`verified-source\`.

To unblock: allow \`www.phonerepairs.nl\` in the environment network policy, or (preferred) request a WordPress
export (WXR via Tools → Export) or read access to \`/wp-json/wp/v2\` from the owner. See docs/migration-plan.md.

## 2. Conflicts found on the original site

| Topic | Values found | Where | Handling in demo |
| --- | --- | --- | --- |
| Warranty | "12 maanden", "90 dagen" and "3 maanden" (even "12 dagen" in one title) | model, area, FAQ and blog pages | Not published; owner must confirm |
| iPhone starting price | "vanaf €60" (homepage, Geldermalsen) and "vanaf €40" (Den Bosch, Vught) | several pages | No starting price shown |
| Pre-owned warranty | "1 jaar" in the text, "90 dagen" in the banner | /pre-owned-toestellen/ | Not published |
| Return shipping cost | €11 and €12 | /veelgestelde-vragen/reparatie-opsturen/ | Not published |
| Years of experience | 10 and 20+ | about pages | Left out of the owner story |
| Customer rating | 9,6 and 9,8 (self-reported) | several pages | Not shown |
| Place names | Pages titled "Oss", "Waalwijk", etc. while the shop is in Den Bosch | area pages | Kept as "Voor <plaats>" pages that say the shop is in Den Bosch |
${crawlConflictRows}

## 3. Missing data

| Item | Status | Needed for |
| --- | --- | --- |
| Repair prices per model | ${prices.filter((p) => p.verified).length} verified (catalog has ${devices.length} models) | Device finder results, device pages, Offer schema |
| Warranty terms | conflicting | Device pages, FAQ |
| WhatsApp number | ${site.whatsapp ? `${site.whatsapp.display} (client-confirmed; +31 6 424 729 54 on the old site is unexplained)` : "not verified — WhatsApp button hidden; +31 6 424 729 54 is listed next to the landline, confirm whether that is WhatsApp"} | Contact actions |
| Postal code | ${site.address.postalCode ?? "missing"} | LocalBusiness schema, contact page |
| Exact opening hours | missing (only "7 dagen per week, ook ’s avonds") | Contact page, OpeningHoursSpecification |
| Original "Over Phone Repairs" text | owner story summarised from snippets; full text not extracted | /over-ons |
| Photos of the shop / technicians | none — generic Adobe Stock photos used (docs/image-credits.md) | Hero, about, process band, CTA |
| Official device photography | none (vector renders used) | Device pages |
| Area landing pages | ${landingPages.filter((p) => p.kind === "area").length} pages live on their original URL with template copy; original text not extracted | Local SEO |
| Blog/news posts | ${blogPosts.length} posts summarised on their original URL; full archive (2+ pages) not exported | Blog |
| Individual FAQ pages under /veelgestelde-vragen/ | ${landingPages.filter((p) => p.kind === "faq-topic").length} kept (zakelijk, opsturen); others redirected or unknown | FAQ migration |
| Prices on original model pages | seen in snippets (e.g. iPhone 16, Galaxy A54, MacBook Pro 16"), not verified | Device pages once confirmed |
| Pre-owned stock and prices | changes often; needs a feed or owner input | /pre-owned-toestellen |
| Terms and privacy pages | not found in the search index | Required before launch |
| Privacy/cookie text for third parties | Trustindex review badge (cdn.trustindex.io) and WhatsApp links | Required before launch |
| Reviews / rating (site mentions 9,8) | not verifiable | Not shown (no fake testimonials) |
| Trade-in / inkoop service | mentioned, not detailed | Possible extra page |
| Full model list per brand | seed catalog only | Device finder completeness |

## 4. Demo content that must be confirmed

- Repair types without a verified source (${demoRepairs.length}): ${demoRepairs.map((r) => r.name).join(", ") || "none"}.
- Devices whose availability is a JUNE Studio seed (${demoBrandsDevices.length} of ${devices.length}): iPad, MacBook, Galaxy A/Z/Tab, Huawei, OnePlus, Xiaomi, Sony, LG models.
- iPhone and Galaxy S lists follow the homepage model menu as seen in a search snapshot (iPhone 7 … Galaxy S26 Ultra).
- All claims, FAQs, kept pages and blog summaries are based on \`search-index\` snapshots and must be re-checked against the live pages.
- Area pages use one template text per place; the original pages each have their own copy, which replaces it after migration.

## 5. URLs without a target on the new site (${unmapped.length})

${unmapped.length ? table(["Original URL", "Type", "Notes"], unmapped.map((r) => [new URL(r.url).pathname, r.pageType, esc(r.notes)])) : "None."}
${
  analysis
    ? `\n## 6. Crawl findings\n\n- Device pages not matched to the catalog: ${analysis.pagesWithoutDevice.length}\n- Prices found but not matched: ${analysis.unmatchedPrices.length}\n- Contact values seen: ${JSON.stringify(analysis.contactValues)}\n`
    : ""
}`;

writeText(join(DOCS_DIR, "content-inventory.md"), inventoryMd);
writeText(join(DOCS_DIR, "url-mapping.csv"), mappingCsv);
writeText(join(DOCS_DIR, "data-gaps.md"), gapsMd);
console.log(`Wrote docs/content-inventory.md, docs/url-mapping.csv (${records.length} URLs), docs/data-gaps.md`);
